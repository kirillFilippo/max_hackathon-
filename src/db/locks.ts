/**
 * Критические секции по ключу (обычно — id события).
 *
 * Нужны там, где решение зависит от предварительного чтения: «есть ли ещё место
 * в составе», «какой номер дать следующей позиции списка покупок». База таких
 * инвариантов не держит (в отличие от уникальности брони), поэтому две
 * одновременные заявки на последнее место обе увидели бы «место есть».
 *
 * Реализация — очередь промисов в процессе бота. Это ровно тот случай, под
 * который рассчитан проект: один процесс и одна база (см. README). Для нескольких
 * реплик понадобится блокировка на стороне БД (advisory-лок или отдельная
 * транзакция с блокировкой строки события) — держите это в голове, если будете
 * масштабировать горизонтально.
 */
export class KeyedLocks {
  private readonly tails = new Map<string, Promise<unknown>>();

  async run<T>(key: string, work: () => Promise<T>): Promise<T> {
    const previous = this.tails.get(key) ?? Promise.resolve();
    // Следующий в очереди стартует независимо от того, чем закончился предыдущий:
    // ошибка одного запроса не должна блокировать остальные.
    const run = previous.then(() => work(), () => work());
    const tail = run.catch(() => undefined);
    this.tails.set(key, tail);
    try {
      return await run;
    } finally {
      // Запись убираем, только если после нас никто не встал в очередь.
      if (this.tails.get(key) === tail) this.tails.delete(key);
    }
  }

  /** Сколько ключей сейчас в очереди: для логов и тестов. */
  size(): number {
    return this.tails.size;
  }
}
